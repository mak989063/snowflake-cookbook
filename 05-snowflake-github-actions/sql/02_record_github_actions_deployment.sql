-- Module 05: GitHub Actions Snowflake CI/CD
-- Purpose: Record each GitHub Actions deployment in Snowflake.
-- Idempotency: Re-running the same pipeline run updates its existing record.

USE DATABASE DEVOPS_LAB_DB;
USE SCHEMA RAW;

MERGE INTO GITHUB_ACTIONS_DEPLOYMENT AS TARGET
USING (
    SELECT
        'SNOWFLAKE-COOKBOOK' AS APPLICATION_NAME,
        '<% deploy_env %>' AS ENVIRONMENT,
        CURRENT_USER() AS DEPLOYED_BY,
        '<% github_run_id %>' AS PIPELINE_RUN_ID
) AS SOURCE
ON TARGET.PIPELINE_RUN_ID = SOURCE.PIPELINE_RUN_ID

WHEN MATCHED THEN UPDATE SET
    TARGET.APPLICATION_NAME = SOURCE.APPLICATION_NAME,
    TARGET.ENVIRONMENT = SOURCE.ENVIRONMENT,
    TARGET.DEPLOYED_BY = SOURCE.DEPLOYED_BY,
    TARGET.DEPLOYED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    APPLICATION_NAME,
    ENVIRONMENT,
    DEPLOYED_BY,
    PIPELINE_RUN_ID
)
VALUES (
    SOURCE.APPLICATION_NAME,
    SOURCE.ENVIRONMENT,
    SOURCE.DEPLOYED_BY,
    SOURCE.PIPELINE_RUN_ID
);
