-- Module 05: GitHub Actions Snowflake CI/CD
-- Purpose: Create a deployment tracking table through GitHub Actions.

USE DATABASE DEVOPS_LAB_DB;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS GITHUB_ACTIONS_DEPLOYMENT (
    DEPLOYMENT_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    APPLICATION_NAME VARCHAR(100) NOT NULL,
    ENVIRONMENT VARCHAR(50) NOT NULL,
    DEPLOYED_BY VARCHAR(100),
    DEPLOYED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PIPELINE_RUN_ID VARCHAR(100)
);

