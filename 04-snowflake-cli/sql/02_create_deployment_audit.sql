-- Create deployment audit table

USE DATABASE DEVOPS_LAB_DB;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS CLI_DEPLOYMENT_AUDIT (
    DEPLOYMENT_KEY VARCHAR(100) NOT NULL,
    APPLICATION_NAME VARCHAR(100),
    ENVIRONMENT VARCHAR(50),
    DEPLOYED_BY VARCHAR(100),
    DEPLOYED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
