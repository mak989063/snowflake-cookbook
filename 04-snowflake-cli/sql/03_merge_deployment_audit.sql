-- Record deployment activity without duplicate deployment keys

USE DATABASE DEVOPS_LAB_DB;
USE SCHEMA RAW;

MERGE INTO CLI_DEPLOYMENT_AUDIT AS TARGET
USING (
    SELECT
        'MODULE04-EXERCISE-02' AS DEPLOYMENT_KEY,
        'SNOWFLAKE-COOKBOOK' AS APPLICATION_NAME,
        '<% deploy_env %>' AS ENVIRONMENT,
        CURRENT_USER() AS DEPLOYED_BY
) AS SOURCE
ON TARGET.DEPLOYMENT_KEY = SOURCE.DEPLOYMENT_KEY

WHEN MATCHED THEN UPDATE SET
    TARGET.DEPLOYED_BY = SOURCE.DEPLOYED_BY,
    TARGET.DEPLOYED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    DEPLOYMENT_KEY,
    APPLICATION_NAME,
    ENVIRONMENT,
    DEPLOYED_BY
)
VALUES (
    SOURCE.DEPLOYMENT_KEY,
    SOURCE.APPLICATION_NAME,
    SOURCE.ENVIRONMENT,
    SOURCE.DEPLOYED_BY
);
